"""Build the experiment configs and run the cloud phase (protocol Sections 9-10; DECISIONS.md §0, §9).

    uv run python scripts/queue.py configs          # configs/matrix, configs/baselines, topologies.yaml
    uv run python scripts/queue.py step1            # Mac: launch + provision one instance (best vCPU/$
                                                    # available), run the smoke re-run there, pull it back
    uv run python scripts/queue.py plan             # Mac: fleet plan from the smoke rates measured there
    uv run python scripts/queue.py coordinate       # Mac: run the fleet (initialized once from step1 + plan)
    uv run python scripts/queue.py run --workers K  # instance: execute results/shard.json

Local queue (scripts/reproduce.sh local; README "run a subset locally"):
    uv run python scripts/queue.py jobs --stage main|sweep|noise [--match GLOB]   # incomplete jobs,
                                                    # one "config seed task" line each, for xargs -P
    uv run python scripts/queue.py select           # qubit-sweep configs from the M1/M2 tf=1.0 runs (6a)
"""

import sys
from pathlib import Path

# This file's name (protocol layout) shadows the stdlib `queue` that torch imports; every script
# in scripts/ therefore removes its own directory from the import path first.
sys.path[:] = [p for p in sys.path if Path(p).resolve() != Path(__file__).resolve().parent]

import argparse  # noqa: E402
import json  # noqa: E402
import time  # noqa: E402
from fnmatch import fnmatch  # noqa: E402

import yaml  # noqa: E402

from qpar import ROOT  # noqa: E402
from qpar import cloud  # noqa: E402
from qpar.models import PLACEMENTS  # noqa: E402
from qpar.quantum import TOPOLOGIES_FILE, TOPOLOGY_SEED, draw_random_edges  # noqa: E402
from qpar.train import RESULTS, config_id, load_base, write_json  # noqa: E402

CONFIGS = ROOT / "configs"
DATASETS = {"mnist": ("M1", "B1"), "fashionmnist": ("M2", "B2")}
ENCODINGS = ("angle", "amplitude")
TOPOLOGIES = ("linear", "fullyconnected", "random")
TRAIN_FRACS = (1.0, 0.5, 0.2)
SWEEP_N = (2, 4, 6, 8)


def write_yaml(path, obj, header=""):
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w") as f:
        f.write(header)
        yaml.safe_dump(obj, f, sort_keys=False, default_flow_style=None)


def main_configs():
    """M1/M2 (54 each) and B1/B2 (21 each) configs, plus the Random-topology edge lists."""
    write_yaml(TOPOLOGIES_FILE,
               {"topology_seed": TOPOLOGY_SEED,
                "random": {n: [list(e) for e in draw_random_edges(n)] for n in SWEEP_N}},
               "# Random topology (protocol 4.5): n-1 distinct pairs drawn uniformly without replacement\n"
               "# from all pairs, numpy default_rng(topology_seed) freshly seeded per n, redrawn from the\n"
               "# same generator while the edge set equals Linear's (decision 4b); edges sorted.\n"
               "# Generated by `scripts/queue.py configs`; tests/test_quantum.py checks it.\n")
    written = 0
    for dataset, (main_block, base_block) in DATASETS.items():
        for placement in PLACEMENTS:
            for encoding in ENCODINGS:
                for topology in TOPOLOGIES:
                    for tf in TRAIN_FRACS:
                        cfg = {"kind": "hybrid", "block": main_block, "dataset": dataset,
                               "placement": placement, "encoding": encoding, "topology": topology,
                               "n_qubits": 4, "train_frac": tf}
                        write_yaml(CONFIGS / "matrix" / f"{config_id(cfg)}.yaml", cfg)
                        written += 1
        for tf in TRAIN_FRACS:
            cfg = {"kind": "base_cnn", "block": base_block, "dataset": dataset, "train_frac": tf}
            write_yaml(CONFIGS / "baselines" / f"{config_id(cfg)}.yaml", cfg)
            written += 1
            for placement in PLACEMENTS:
                for encoding in ENCODINGS:
                    cfg = {"kind": "matched", "block": base_block, "dataset": dataset,
                           "placement": placement, "encoding": encoding, "n_qubits": 4, "train_frac": tf}
                    write_yaml(CONFIGS / "baselines" / f"{config_id(cfg)}.yaml", cfg)
                    written += 1
    return written


def cmd_step1(base, poll=30):
    """Step 1 of the cloud plan: one instance, the smoke re-run (2a) across its cores."""
    cloud.require_credentials()
    types = cloud.available_types()
    if not types:
        raise SystemExit("no allowed instance type has capacity")
    type_name, region, vcpus, usd = types[0]
    for attempt in (1, 2):
        try:
            instance_id = cloud.launch_instance(type_name, region, "qpar-1")
            break
        except Exception as exc:
            cloud.event("ERROR", f"step 1 launch attempt {attempt} failed: {exc!r}")
            if attempt == 2:
                cloud.event("STOP", "15.6: instance creation failed twice")
                raise SystemExit(1) from None
            time.sleep(30)
    record = {"id": instance_id, "type": type_name, "region": region, "vcpus": vcpus, "usd_per_hour": usd,
              "launched_at": time.time()}
    write_json(cloud.FLEET / "step1.json", record)
    cloud.event("LAUNCH", f"qpar-1 {type_name} {region} ${usd}/h (step 1)")
    record["ip"] = cloud.wait_active(instance_id)
    write_json(cloud.FLEET / "step1.json", record)
    record["workers"] = cloud.provision(record["ip"])
    write_json(cloud.FLEET / "step1.json", record)
    cloud.event("READY", f"qpar-1 {record['workers']} workers; unit tests passed there")
    uv = cloud.UV
    cloud.ssh(record["ip"], f"cd {cloud.REMOTE} && mkdir -p results/smoke && rm -f results/smoke/.done && "
                            f"(nohup sh -c 'OMP_NUM_THREADS=1 {uv} run python scripts/smoke.py archs --workers "
                            f"{record['workers']} > results/smoke/archs.out 2>&1; OMP_NUM_THREADS=1 {uv} run python "
                            f"scripts/smoke.py noise > results/smoke/noise.out 2>&1; echo $? > results/smoke/.done' "
                            f"> /dev/null 2>&1 < /dev/null &)", timeout=120)
    t0 = time.time()
    while cloud.ssh(record["ip"], f"test -f {cloud.REMOTE}/results/smoke/.done", check=False, timeout=60).returncode:
        time.sleep(poll)
    cloud.rsync(f"ubuntu@{record['ip']}:{cloud.REMOTE}/results/smoke/", f"{RESULTS / 'smoke'}/")
    archs = json.loads((RESULTS / "smoke" / "archs.json").read_text())
    noise = json.loads((RESULTS / "smoke" / "noise.json").read_text())
    passed = sum(r["pass"] for r in archs["rows"])
    green = archs["all_pass"] and noise["all_pass"]
    cloud.event("SMOKE", f"{'GREEN' if green else 'RED'}: {passed}/{len(archs['rows'])} archs pass, noise gates "
                         f"{'pass' if noise['all_pass'] else 'FAIL'}; {(time.time() - t0) / 60:.0f} min on qpar-1")
    return green


def cmd_plan(base):
    archs = json.loads((RESULTS / "smoke" / "archs.json").read_text())
    noise = json.loads((RESULTS / "smoke" / "noise.json").read_text())
    step1 = json.loads((cloud.FLEET / "step1.json").read_text())
    model = cloud.CostModel(archs, noise, base["training"]["epochs"])
    itype = {"name": step1["type"], "vcpus": step1["vcpus"], "usd_per_hour": step1["usd_per_hour"]}
    plan = cloud.plan_fleet(model, base, itype, cores=step1["workers"])
    plan["prior_spend_usd"] = step1.get("cost_usd", 0.0)
    plan["projected_total_usd"] = plan["prior_spend_usd"] + plan["chosen"]["usd"]
    write_json(cloud.FLEET / "plan.json", plan)
    for name, sc in plan["scenarios"].items():
        print(f"sweep winners all {name}: floor {sc['floor_hours']:.1f} h")
        for f in sc["fleets"]:
            print(f"   {f['instances']} x {itype['name']} ({f['workers']} workers): {f['wall_hours']:.1f} h, "
                  f"{f['instance_hours']:.0f} instance-h, ${f['usd']:.0f}, {f['ratio_to_floor']:.2f} x floor")
    print(f"chosen: {plan['chosen']}; projected total ${plan['projected_total_usd']:.0f}")
    return plan


def cmd_coordinate(base, interval):
    archs = json.loads((RESULTS / "smoke" / "archs.json").read_text())
    noise = json.loads((RESULTS / "smoke" / "noise.json").read_text())
    coordinator = cloud.Coordinator(base, cloud.CostModel(archs, noise, base["training"]["epochs"]), interval=interval)
    if coordinator.state is None:
        plan = json.loads((cloud.FLEET / "plan.json").read_text())
        coordinator.initialize(plan, prior_spend=plan["prior_spend_usd"])
    coordinator.run()


STAGES = {"main": ("matrix", "baselines"), "sweep": ("sweep",), "noise": ("matrix", "sweep")}


def cmd_jobs(base, stage, match):
    """The incomplete jobs of a stage in Section 9 order (blocks M1, B1, M2, B2, S; train_frac
    descending within a block; noise last), one "config seed task" line each."""
    paths = [p for d in STAGES[stage] for p in sorted((CONFIGS / d).glob("*.yaml")) if fnmatch(p.stem, match)]
    jobs = [j for j in cloud.jobs_for(paths, base["seeds"], cloud.noise_parts_of(base))
            if (j.task != "train") == (stage == "noise")]
    jobs.sort(key=lambda j: (cloud.BLOCK_ORDER.index(j.block), -j.train_frac))
    for job in jobs:
        if not cloud.job_complete(job, base["training"]["epochs"]):
            print(job.config_path, job.seed, job.task)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="cmd", required=True)
    sub.add_parser("configs", help="write the M1/M2/B1/B2 configs and topologies.yaml")
    jobs = sub.add_parser("jobs", help="local queue: the incomplete jobs of a stage")
    jobs.add_argument("--stage", choices=tuple(STAGES), required=True)
    jobs.add_argument("--match", default="*", help="config-id glob, e.g. 'mnist_post_*_tf1.0'")
    sub.add_parser("select", help="local queue: the qubit-sweep selection (decision 6a)")
    sub.add_parser("step1", help="one instance + the smoke re-run there")
    sub.add_parser("plan", help="fleet plan from the cloud smoke rates")
    coord = sub.add_parser("coordinate", help="run the fleet")
    coord.add_argument("--interval", type=int, default=120)
    run = sub.add_parser("run", help="instance side: execute results/shard.json")
    run.add_argument("--workers", type=int, required=True)
    args = parser.parse_args(argv)
    base = load_base()
    if args.cmd == "configs":
        print(f"wrote {main_configs()} config files and {TOPOLOGIES_FILE.relative_to(ROOT)}")
    elif args.cmd == "jobs":
        cmd_jobs(base, args.stage, args.match)
    elif args.cmd == "select":
        for dataset in DATASETS:
            selection = cloud.select_sweep(dataset, base["seeds"])
            print(dataset, {pl: f"{s['encoding']}/{s['topology']}" for pl, s in selection.items()})
    elif args.cmd == "step1":
        return 0 if cmd_step1(base) else 1
    elif args.cmd == "plan":
        cmd_plan(base)
    elif args.cmd == "coordinate":
        cmd_coordinate(base, args.interval)
    elif args.cmd == "run":
        cloud.run_instance(args.workers, base)


if __name__ == "__main__":
    sys.exit(main())
