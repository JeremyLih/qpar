"""Plain-text exports for the paper's appendix (DECISIONS.md §14).

    uv run python scripts/appendix.py   # results/appendix/random_topology_edges.txt: Random edge lists,
                                        #   n = 6 and 8, with the draw rule (configs/topologies.yaml)
                                        # results/appendix/sweep_gate_counts.txt: G and two-qubit gates
                                        #   after transpilation per sweep configuration (summary.csv)
"""

import sys
from pathlib import Path

sys.path[:] = [p for p in sys.path if Path(p).resolve() != Path(__file__).resolve().parent]  # see queue.py

import pandas as pd  # noqa: E402
import yaml  # noqa: E402

from qpar import ROOT  # noqa: E402
from qpar.quantum import TOPOLOGIES_FILE, TOPOLOGY_SEED  # noqa: E402
from qpar.train import RESULTS  # noqa: E402

OUT = RESULTS / "appendix"
NAMES = {"pre": "Pre", "middle": "Middle", "post": "Post", "linear": "Linear", "random": "Random",
         "fullyconnected": "FullyConnected", "mnist": "MNIST", "fashionmnist": "Fashion-MNIST"}


def random_edges():
    topo = yaml.safe_load(open(TOPOLOGIES_FILE))
    assert topo["topology_seed"] == TOPOLOGY_SEED
    lines = [
        "# Random-topology edge lists for n = 6 and n = 8 (appendix).",
        f"# Source: code/configs/topologies.yaml, generated by qpar.quantum.draw_random_edges (seed {TOPOLOGY_SEED}).",
        "# Rule: n-1 distinct qubit pairs drawn uniformly without replacement from all n(n-1)/2 pairs with",
        f"#   numpy.random.default_rng({TOPOLOGY_SEED}), freshly seeded for each n; if the drawn set equals the Linear",
        "#   chain {(0,1), (1,2), ..., (n-2,n-1)}, draw again from the same generator; edges sorted.",
        "#   The redraw was needed only at n = 4 (first draw = Linear chain; kept draw = star",
        "#   {(0,1), (0,2), (0,3)}). At n = 6 and n = 8 the first draw was kept.",
        "# Each edge (c, t) is one CNOT with control c and target t, applied in the listed order after the",
        "#   Rot gates of each of the L = 3 variational layers. Qubits are numbered 0 to n-1.",
        "",
    ]
    for n in (6, 8):
        es = [tuple(e) for e in topo["random"][n]]
        untouched = sorted(set(range(n)) - {q for e in es for q in e})
        lines.append(f"n = {n}: " + ", ".join(f"({a},{b})" for a, b in es))
        lines.append(f"       {len(es)} CNOTs per layer; no CNOT acts on qubit {', '.join(map(str, untouched))}")
    (OUT / "random_topology_edges.txt").write_text("\n".join(lines) + "\n")


def sweep_gate_counts():
    s = pd.read_csv(RESULTS / "summary.csv")
    runs = pd.read_csv(RESULTS / "runs.csv")
    sw = s[(s.kind == "hybrid") & s.n_qubits.isin([2, 6, 8])].copy()
    assert len(sw) == 18
    per_run = runs[runs.config_id.isin(sw.config_id)].groupby("config_id")[["G", "twoq_transpiled"]].nunique()
    assert (per_run == 1).all().all()  # one transpilation per architecture, identical across seeds
    sw["ds_order"] = sw.dataset.map({"mnist": 0, "fashionmnist": 1})
    sw["pl_order"] = sw.placement.map({"pre": 0, "middle": 1, "post": 2})
    sw = sw.sort_values(["ds_order", "pl_order", "n_qubits"])
    hdr = ["dataset", "n", "placement", "encoding", "topology", "G", "2Q_transpiled"]
    rows = [[NAMES[r.dataset], str(int(r.n_qubits)), NAMES[r.placement], r.encoding, NAMES[r.topology],
             str(int(r.G)), str(int(r.twoq_transpiled))] for r in sw.itertuples()]
    w = [max(len(x) for x in col) for col in zip(hdr, *rows)]

    def fmt(r):
        return "  ".join(c.ljust(w[i]) if i < 5 else c.rjust(w[i]) for i, c in enumerate(r)).rstrip()

    text = [
        "# Qubit-sweep configurations (n = 2, 6, 8; train_frac = 1.0; both datasets): gate counts (appendix).",
        "# Source: code/results/summary.csv, rows kind = hybrid with n_qubits in {2, 6, 8}; columns G, twoq_transpiled.",
        "# G: gates of the quantum block after decomposition to {RX, RY, RZ, CNOT}, encoding gates included",
        "#   (Rot = 3 gates; amplitude encoding counted at its full Möttönen structure).",
        "# 2Q_transpiled: two-qubit gates after transpilation to FakeAachen (qiskit-ibm-runtime 0.50.0, IBM Heron r3,",
        "#   156 qubits, calibration 2026-04-17), optimization_level 1, seed_transpiler 0; one transpilation per architecture.",
        "# The n = 4 point of each sweep line is the corresponding main-grid configuration (not listed here).",
        "",
        fmt(hdr), fmt(["-" * x for x in w]), *map(fmt, rows),
    ]
    (OUT / "sweep_gate_counts.txt").write_text("\n".join(text) + "\n")


if __name__ == "__main__":
    OUT.mkdir(exist_ok=True)
    random_edges()
    sweep_gate_counts()
    print("wrote", *(p.relative_to(ROOT) for p in sorted(OUT.glob("*.txt"))))
